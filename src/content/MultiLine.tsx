import { Fragment } from 'react';

// Shows line breaks typed into a heading field in /admin.
export default function MultiLine({ text }: { text: string }) {
  return (
    <>
      {text.split('\n').map((line, i) => (
        <Fragment key={i}>
          {i > 0 && <br />}
          {line}
        </Fragment>
      ))}
    </>
  );
}
